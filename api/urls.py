@api_view(["GET"])
def api_root_view(request, format=None):
    """API root: lists every argument-free endpoint by its route name."""
    base_url = request.build_absolute_uri("/api/")
    endpoints = {}
    for p in api_patterns:
        route = str(p.pattern)
        if "<" in route or not getattr(p, "name", None):
            continue
        endpoints.setdefault(p.name, base_url + route)
    return Response({
        "message": "Vet Portal API",
        "version": "2.0",
        "endpoints": dict(sorted(endpoints.items())),
    })


